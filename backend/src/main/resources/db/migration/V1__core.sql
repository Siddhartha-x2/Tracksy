CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL CHECK (length(trim(name)) BETWEEN 2 AND 100),
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('student','faculty','admin')),
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_lower ON users(lower(email));
CREATE TABLE projects (
 id VARCHAR(40) PRIMARY KEY,
 name VARCHAR(120) NOT NULL CHECK (length(trim(name)) BETWEEN 2 AND 120),
 description VARCHAR(4000) NOT NULL DEFAULT '',
 term VARCHAR(100) NOT NULL DEFAULT '',
 problem_statement VARCHAR(4000) NOT NULL DEFAULT '',
 tech_stack VARCHAR(1000) NOT NULL DEFAULT '',
 start_date DATE,
 deadline DATE,
 status VARCHAR(20) NOT NULL DEFAULT 'Planning' CHECK (status IN ('Planning','Active','Completed','Archived')),
 join_code VARCHAR(32) NOT NULL UNIQUE,
 faculty_owner_id BIGINT NOT NULL REFERENCES users(id),
 supervision_status VARCHAR(20) NOT NULL DEFAULT 'Approved' CHECK(supervision_status IN ('Pending','Approved','Declined')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (start_date IS NULL OR deadline IS NULL OR start_date <= deadline)
);
CREATE TABLE project_members (
 project_id VARCHAR(40) NOT NULL REFERENCES projects(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 project_role VARCHAR(20) NOT NULL DEFAULT 'member' CHECK (project_role IN ('member','leader','faculty')),
 responsibility VARCHAR(1000) NOT NULL DEFAULT '',
 active BOOLEAN NOT NULL DEFAULT TRUE,
 joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(project_id,user_id)
);
CREATE UNIQUE INDEX project_single_active_leader ON project_members(project_id) WHERE active AND project_role='leader';
CREATE TABLE invitations (
 id VARCHAR(64) PRIMARY KEY,
 project_id VARCHAR(40) NOT NULL REFERENCES projects(id),
 email VARCHAR(254) NOT NULL,
 invited_by BIGINT NOT NULL REFERENCES users(id),
 status VARCHAR(20) NOT NULL DEFAULT 'Pending' CHECK(status IN ('Pending','Accepted','Declined','Expired')),
 expires_at TIMESTAMPTZ NOT NULL,
 responded_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX invitation_pending_email ON invitations(project_id,lower(email)) WHERE status='Pending';
CREATE TABLE join_requests (
 id VARCHAR(40) PRIMARY KEY,
 project_id VARCHAR(40) NOT NULL REFERENCES projects(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 status VARCHAR(20) NOT NULL DEFAULT 'Pending' CHECK(status IN ('Pending','Accepted','Declined')),
 decided_by BIGINT REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 decided_at TIMESTAMPTZ,
 UNIQUE(project_id,user_id)
);
CREATE TABLE tasks (
 id VARCHAR(40) PRIMARY KEY,
 project_id VARCHAR(40) NOT NULL REFERENCES projects(id),
 name VARCHAR(160) NOT NULL CHECK(length(trim(name)) BETWEEN 2 AND 160),
 details VARCHAR(4000) NOT NULL DEFAULT '',
 assigned_to BIGINT NOT NULL,
 created_by BIGINT NOT NULL REFERENCES users(id),
 due_date DATE,
 priority VARCHAR(20) NOT NULL DEFAULT 'Medium' CHECK(priority IN ('Low','Medium','High')),
 complexity INTEGER NOT NULL DEFAULT 1 CHECK(complexity BETWEEN 1 AND 5),
 points INTEGER NOT NULL CHECK(points BETWEEN 1 AND 25),
 status VARCHAR(30) NOT NULL DEFAULT 'To do' CHECK(status IN ('To do','In progress','Blocked','Under review','Done')),
 acceptance_criteria VARCHAR(4000) NOT NULL DEFAULT '',
 milestone_id VARCHAR(40),
 parent_task_id VARCHAR(40) REFERENCES tasks(id),
 blocker VARCHAR(1000) NOT NULL DEFAULT '',
 version INTEGER NOT NULL DEFAULT 1,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 FOREIGN KEY(project_id,assigned_to) REFERENCES project_members(project_id,user_id),
 CHECK (parent_task_id IS NULL OR parent_task_id <> id)
);
CREATE TABLE task_dependencies (
 task_id VARCHAR(40) NOT NULL REFERENCES tasks(id),
 depends_on_task_id VARCHAR(40) NOT NULL REFERENCES tasks(id),
 PRIMARY KEY(task_id,depends_on_task_id),
 CHECK(task_id<>depends_on_task_id)
);
CREATE TABLE task_comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id VARCHAR(40) NOT NULL REFERENCES tasks(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 body VARCHAR(2000) NOT NULL CHECK(length(trim(body)) BETWEEN 1 AND 2000),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE task_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id VARCHAR(40) NOT NULL REFERENCES tasks(id),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 action VARCHAR(100) NOT NULL,
 details VARCHAR(4000) NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE evidence (
 id VARCHAR(40) PRIMARY KEY,
 task_id VARCHAR(40) NOT NULL REFERENCES tasks(id),
 student_id BIGINT NOT NULL REFERENCES users(id),
 status VARCHAR(30) NOT NULL DEFAULT 'Under review' CHECK(status IN ('Under review','Approved','Changes requested','Rejected')),
 current_version INTEGER NOT NULL DEFAULT 1 CHECK(current_version>=1),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(task_id,student_id)
);
CREATE TABLE evidence_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 evidence_id VARCHAR(40) NOT NULL REFERENCES evidence(id),
 version INTEGER NOT NULL CHECK(version>=1),
 title VARCHAR(160) NOT NULL CHECK(length(trim(title)) BETWEEN 2 AND 160),
 note VARCHAR(4000) NOT NULL DEFAULT '',
 work_link VARCHAR(2000) NOT NULL DEFAULT '',
 original_filename VARCHAR(255),
 stored_filename VARCHAR(100),
 content_type VARCHAR(100),
 file_size BIGINT,
 submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(evidence_id,version)
);
CREATE TABLE evidence_reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 evidence_version_id BIGINT NOT NULL UNIQUE REFERENCES evidence_versions(id),
 faculty_id BIGINT NOT NULL REFERENCES users(id),
 decision VARCHAR(30) NOT NULL CHECK(decision IN ('Approved','Changes requested','Rejected')),
 feedback VARCHAR(1000) NOT NULL DEFAULT '',
 quality INTEGER CHECK(quality BETWEEN 1 AND 5),
 reviewed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX member_user_active ON project_members(user_id,active);
CREATE INDEX task_project_status ON tasks(project_id,status);
CREATE INDEX task_assignee ON tasks(assigned_to,project_id);
CREATE INDEX evidence_student_status ON evidence(student_id,status);
CREATE INDEX invitation_email ON invitations(lower(email),status);
CREATE TABLE spring_session (
 primary_id CHAR(36) PRIMARY KEY,
 session_id CHAR(36) NOT NULL,
 creation_time BIGINT NOT NULL,
 last_access_time BIGINT NOT NULL,
 max_inactive_interval INTEGER NOT NULL,
 expiry_time BIGINT NOT NULL,
 principal_name VARCHAR(254)
);
CREATE UNIQUE INDEX spring_session_id ON spring_session(session_id);
CREATE INDEX spring_session_expiry ON spring_session(expiry_time);
CREATE INDEX spring_session_principal ON spring_session(principal_name);
CREATE TABLE spring_session_attributes (
 session_primary_id CHAR(36) NOT NULL REFERENCES spring_session(primary_id) ON DELETE CASCADE,
 attribute_name VARCHAR(200) NOT NULL,
 attribute_bytes BYTEA NOT NULL,
 PRIMARY KEY(session_primary_id,attribute_name)
);
