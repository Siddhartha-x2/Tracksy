CREATE TABLE milestones (
 id VARCHAR(40) PRIMARY KEY,
 project_id VARCHAR(40) NOT NULL REFERENCES projects(id),
 title VARCHAR(160) NOT NULL CHECK(length(trim(title)) BETWEEN 2 AND 160),
 description VARCHAR(4000) NOT NULL DEFAULT '',
 due_date DATE NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'Planned' CHECK(status IN ('Planned','In progress','Completed')),
 approved_by BIGINT REFERENCES users(id),
 approved_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((status='Completed') = (approved_by IS NOT NULL))
);
ALTER TABLE tasks ADD CONSTRAINT task_milestone_fk FOREIGN KEY(milestone_id) REFERENCES milestones(id);
CREATE TABLE weekly_logs (
 id VARCHAR(40) PRIMARY KEY,
 project_id VARCHAR(40) NOT NULL REFERENCES projects(id),
 user_id BIGINT NOT NULL,
 week_start DATE NOT NULL CHECK(extract(isodow from week_start)=1),
 completed_work VARCHAR(4000) NOT NULL CHECK(length(trim(completed_work))>=10),
 next_plan VARCHAR(4000) NOT NULL CHECK(length(trim(next_plan))>=10),
 blockers VARCHAR(2000) NOT NULL DEFAULT '',
 hours NUMERIC(5,2) NOT NULL CHECK(hours BETWEEN 0 AND 168),
 feedback VARCHAR(2000) NOT NULL DEFAULT '',
 quality INTEGER CHECK(quality BETWEEN 1 AND 5),
 reviewed_by BIGINT REFERENCES users(id),
 reviewed_at TIMESTAMPTZ,
 revision INTEGER NOT NULL DEFAULT 1,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(project_id,user_id,week_start),
 FOREIGN KEY(project_id,user_id) REFERENCES project_members(project_id,user_id)
);
CREATE TABLE log_tasks (
 log_id VARCHAR(40) NOT NULL REFERENCES weekly_logs(id),
 task_id VARCHAR(40) NOT NULL REFERENCES tasks(id),
 PRIMARY KEY(log_id,task_id)
);
CREATE TABLE weekly_log_versions (
 log_id VARCHAR(40) NOT NULL REFERENCES weekly_logs(id),
 revision INTEGER NOT NULL,
 snapshot JSONB NOT NULL,
 saved_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(log_id,revision)
);
CREATE TABLE peer_reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id VARCHAR(40) NOT NULL REFERENCES projects(id),
 reviewer_id BIGINT NOT NULL,
 reviewee_id BIGINT NOT NULL,
 period VARCHAR(40) NOT NULL CHECK(length(trim(period)) BETWEEN 2 AND 40),
 collaboration INTEGER NOT NULL CHECK(collaboration BETWEEN 1 AND 5),
 communication INTEGER NOT NULL CHECK(communication BETWEEN 1 AND 5),
 reliability INTEGER NOT NULL CHECK(reliability BETWEEN 1 AND 5),
 feedback VARCHAR(2000) NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(project_id,reviewer_id,reviewee_id,period),
 CHECK(reviewer_id<>reviewee_id),
 FOREIGN KEY(project_id,reviewer_id) REFERENCES project_members(project_id,user_id),
 FOREIGN KEY(project_id,reviewee_id) REFERENCES project_members(project_id,user_id)
);
CREATE TABLE score_rubrics (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id VARCHAR(40) NOT NULL REFERENCES projects(id),
 version INTEGER NOT NULL CHECK(version>=1),
 tasks INTEGER NOT NULL CHECK(tasks BETWEEN 0 AND 100),
 evidence INTEGER NOT NULL CHECK(evidence BETWEEN 0 AND 100),
 consistency INTEGER NOT NULL CHECK(consistency BETWEEN 0 AND 100),
 peer INTEGER NOT NULL CHECK(peer BETWEEN 0 AND 100),
 repository INTEGER NOT NULL CHECK(repository BETWEEN 0 AND 100),
 documentation INTEGER NOT NULL CHECK(documentation BETWEEN 0 AND 100),
 milestones INTEGER NOT NULL CHECK(milestones BETWEEN 0 AND 100),
 created_by BIGINT NOT NULL REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(project_id,version),
 CHECK(tasks+evidence+consistency+peer+repository+documentation+milestones=100)
);
CREATE TABLE audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id VARCHAR(40) REFERENCES projects(id),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 action VARCHAR(100) NOT NULL,
 entity_type VARCHAR(100) NOT NULL,
 entity_id VARCHAR(100) NOT NULL,
 details VARCHAR(4000) NOT NULL DEFAULT '',
 visibility_user_id BIGINT REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 project_id VARCHAR(40) REFERENCES projects(id),
 title VARCHAR(160) NOT NULL,
 body VARCHAR(2000) NOT NULL,
 dedupe_key VARCHAR(200) UNIQUE,
 read_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE repository_integrations (
 project_id VARCHAR(40) PRIMARY KEY REFERENCES projects(id),
 owner VARCHAR(39) NOT NULL,
 name VARCHAR(100) NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'Configured' CHECK(status IN ('Configured','Synced','Error')),
 sync_error VARCHAR(500),
 last_synced_at TIMESTAMPTZ,
 inspected_commits INTEGER NOT NULL DEFAULT 0,
 sample_truncated BOOLEAN NOT NULL DEFAULT FALSE,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE repository_identities (
 project_id VARCHAR(40) NOT NULL REFERENCES repository_integrations(project_id),
 user_id BIGINT NOT NULL,
 github_username VARCHAR(39) NOT NULL,
 verified_by BIGINT NOT NULL REFERENCES users(id),
 verified_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(project_id,user_id),
 UNIQUE(project_id,github_username),
 FOREIGN KEY(project_id,user_id) REFERENCES project_members(project_id,user_id)
);
CREATE TABLE repository_commits (
 project_id VARCHAR(40) NOT NULL REFERENCES repository_integrations(project_id),
 sha VARCHAR(64) NOT NULL,
 github_username VARCHAR(39),
 committed_at TIMESTAMPTZ NOT NULL,
 message VARCHAR(500) NOT NULL,
 PRIMARY KEY(project_id,sha)
);
CREATE INDEX milestone_project ON milestones(project_id);
CREATE INDEX weekly_log_project_user ON weekly_logs(project_id,user_id,week_start);
CREATE INDEX peer_review_project_reviewee ON peer_reviews(project_id,reviewee_id);
CREATE INDEX audit_project_created ON audit_events(project_id,created_at DESC);
CREATE INDEX notification_unread_user ON notifications(user_id) WHERE read_at IS NULL;
